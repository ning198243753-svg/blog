    "  if (to.meta.requiresAuth && !authStore.checked) {",
    "    await authStore.fetchMe()      // 调 GET /api/auth/me",
    "  }",
    "",
    "  // 2. 未登录 → 跳登录页，并记住原目标（登录后跳回）",
    "  if (to.meta.requiresAuth && !authStore.isLoggedIn) {",
    "    return { path: '/admin/login', query: { redirect: to.fullPath } }",
    "  }",
    "",
    "  // 3. 已登录访问登录页 → 直接进后台",
